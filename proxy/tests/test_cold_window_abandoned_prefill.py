class _ChunkAiter:
    """Async iterator over pre-baked chunks, optionally blocking at the end."""

    def __init__(self, chunks: list[bytes], *, block_forever: bool = False):
        self._chunks = list(chunks)
        self._block_forever = block_forever
        self._generator = self._generate()

    async def _generate(self):
        for chunk in self._chunks:
            yield chunk
        if self._block_forever:
            await asyncio.Event().wait()  # never resolves

    def __aiter__(self):
        return self

    def __anext__(self):
        return self._generator.__anext__()


@pytest.mark.asyncio
async def test_peek_keeps_the_latest_progress_for_the_abandonment_sample():
    """The peek refreshes the latest observation while only the first decides."""
    from proxy.measured_cache_abort import AbortSettings

    chunks = [
        _progress_event(90_000, 89_000, 89_000, 0),
        _progress_event(90_000, 89_000, 89_800, 150_000),
        _progress_event(90_000, 89_000, 90_000, 180_100),
        _CONTENT_CHUNK,
    ]
    latest: list[Any] = []
    prefetch = await helpers._prefetch_measured_cache_abort(
        _ChunkAiter(chunks),
        SSEEventReframer(),
        settings=AbortSettings(enabled=True, bound_tokens=2_000, min_deficit_ratio=0.25),
        priced_new_tokens=1_000,
        timeout=1.0,
        latest_sink=latest,
    )
    # The deciding measurement is still the FIRST event (its cache is final)...
    assert prefetch.measured is not None
    assert prefetch.measured.processed == 89_000
    # ...while the abandonment sample prices the progress actually reached.
    assert prefetch.latest_measured is not None
    assert prefetch.latest_measured.processed == 90_000
    assert latest == [prefetch.latest_measured]


@pytest.mark.asyncio
async def test_cancelled_peek_still_leaves_the_latest_progress_with_the_caller():
    """The deadline cancels the peek — the sample must still have its evidence.

    This is the certification path: the peek is bounded by the prefill deadline,
    so on a real abandonment it is *cancelled*, never returned. The
    ``latest_sink`` is what makes that observation survive.
    """
    from proxy.measured_cache_abort import AbortSettings

    chunks = [
        _progress_event(90_000, 89_000, 89_000, 0),
        _progress_event(90_000, 89_000, 90_000, 180_100),
    ]
    latest: list[Any] = []
    task = asyncio.ensure_future(
        helpers._prefetch_measured_cache_abort(
            _ChunkAiter(chunks, block_forever=True),
            SSEEventReframer(),
            settings=AbortSettings(enabled=True),
            priced_new_tokens=1_000,
            timeout=0,
            latest_sink=latest,
        )
    )
    # Let the peek consume both progress events, then cancel it the way the
    # deadline monitor does.
    for _ in range(50):
        if latest:
            break
        await asyncio.sleep(0.01)
    assert latest, "the peek must publish progress before it is cancelled"
    task.cancel()
    with pytest.raises(asyncio.CancelledError):
        await task
    assert latest[0].processed == 90_000
    assert latest[0].time_ms == 180_100


