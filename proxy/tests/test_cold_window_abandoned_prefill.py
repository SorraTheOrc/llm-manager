def _fixture_records() -> list[dict]:
    records = [
        json.loads(line)
        for line in FIXTURE.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    assert records, f"fixture {FIXTURE} is empty"
    assert "_meta" in records[0], "fixture header missing"
    return records[1:]


def _load_window(kinds: Iterable[str] = ("abandoned", "completed")) -> list[dict]:
    """Feed the fixture's prefill evidence into the cold window.

    Returns the rows the recorder actually **accepted** — the exact population
    the assertions below derive the expected rate from.
    """
    accepted: list[dict] = []
    wanted = set(kinds)
    for record in _fixture_records():
        if record["kind"] not in wanted:
            continue
        if record["kind"] == "abandoned":
            recorded = prefill_eta.record_abandoned_prefill_sample(
                MODEL,
                record["total"],
                record["cache"],
                record["processed"],
                record["time_ms"],
            )
        else:
            prefill_eta.record_cold_measured_sample(
                MODEL,
                record["total"],
                record["measured_cached_ratio"],
                record["processed"],
                record["time_ms"],
            )
            recorded = True
        if recorded:
            accepted.append(record)
    return accepted


def _expected_raw_rate(rows: Iterable[dict]) -> float:
    """The least-squares-through-origin rate the recorded rows imply.

    Every accepted row is recorded as ``(cached=0, new=processed, ms=time_ms)``
    (the abandonment path claims no cache credit — see
    :func:`prefill_eta.record_abandoned_prefill_sample`), so the cold window's
    raw fit is ``sum(new*ms) / sum(new^2)`` over exactly these rows.
    """
    rows = list(rows)
    numerator = sum(row["processed"] * row["time_ms"] for row in rows)
    denominator = sum(row["processed"] ** 2 for row in rows)
    assert denominator > 0
    return numerator / denominator


def _replay_rows() -> list[dict]:
    return [r for r in _fixture_records() if r["kind"] == "replay"]


def _cold_capacity(tokens: int, config: dict) -> prefill_eta.DeadlineCapacity:
    return prefill_eta.deadline_capacity(MODEL, tokens, config)


