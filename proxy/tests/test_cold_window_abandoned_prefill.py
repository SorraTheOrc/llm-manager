def test_recorder_accepts_an_abandoned_cold_prefill_and_prices_positions():
    """The sample is ``(cached=0, new=positions, ms=elapsed)`` — no double count.

    The elapsed time already covers every position the prefill traversed, so a
    cache credit for the same tokens would double-count them and make the cold
    window more optimistic than the prior it exists to correct.
    """
    assert prefill_eta.record_abandoned_prefill_sample(
        MODEL, 80_000, 4_000, 40_000, 180_100.0
    )
    coeffs = prefill_eta.coefficients(MODEL, 80_000, _cfg(), cached_ratio=0.0)
    assert coeffs.cold_samples == 1
    assert coeffs.calibrated is False  # one sample never calibrates a bucket
    # A full window of the same observation prices the positions it traversed.
    for _ in range(prefill_eta.MIN_CALIBRATION_SAMPLES - 1):
        assert prefill_eta.record_abandoned_prefill_sample(
            MODEL, 80_000, 4_000, 40_000, 180_100.0
        )
    coeffs = prefill_eta.coefficients(MODEL, 80_000, _cfg(), cached_ratio=0.0)
    assert coeffs.calibrated is True
    assert coeffs.prefill_ms_per_token == pytest.approx(
        180_100.0 / 40_000 * prefill_eta.CONSERVATISM_FACTOR, rel=1e-9
    )
    # The coded term kept its unsettled default: the sample never claimed one.
    assert coeffs.coded_ms_per_token == prefill_eta.DEFAULT_CODED_MS_PER_TOKEN


