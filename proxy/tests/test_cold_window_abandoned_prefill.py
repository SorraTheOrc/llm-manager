def test_rollback_key_default_and_values():
    """Absent keeps the target behaviour; an explicit false restores pre-change."""
    assert prefill_eta.EVICTION_COLD_SAMPLE_KEY == "local_deadline_cold_sample_enabled"
    assert prefill_eta.eviction_cold_sample_enabled(None) is True
    assert prefill_eta.eviction_cold_sample_enabled({}) is True
    assert prefill_eta.eviction_cold_sample_enabled({"server": {}}) is True
    # A flat dict is tolerated (hand-built configs / tests).
    assert prefill_eta.eviction_cold_sample_enabled({"server": {}}) is True
    for off in (0, False, "0", "false", "off", "disabled", ""):
        assert (
            prefill_eta.eviction_cold_sample_enabled(
                {"server": {prefill_eta.EVICTION_COLD_SAMPLE_KEY: off}}
            )
            is False
        )
    for on in (1, True, "1", "true", "on", "enabled"):
        assert (
            prefill_eta.eviction_cold_sample_enabled(
                {"server": {prefill_eta.EVICTION_COLD_SAMPLE_KEY: on}}
            )
            is True
        )
    # Present but unreadable fails open to the pre-change behaviour.
    assert (
        prefill_eta.eviction_cold_sample_enabled(
            {"server": {prefill_eta.EVICTION_COLD_SAMPLE_KEY: object()}}
        )
        is False
    )


def test_rollback_key_restores_the_pre_change_cold_window():
    """With the key off the fixture's abandoned rows cannot calibrate anything."""
    config = _cfg(local_deadline_cold_sample_enabled=0)
    assert prefill_eta.eviction_cold_sample_enabled(config) is False
    # Nothing is recorded when the wiring is off (the guard lives at the call
    # site), so the window behaves exactly as it did before this item.
    assert prefill_eta.coefficients(MODEL, 90_000, config).cold_samples == 0
    decision = prefill_eta.evaluate_admission(
        config, MODEL, 90_000, 0.0, "low", residency_measured=False
    )
    assert decision.admit is True
    assert decision.deadline_capacity_calibrated is False


