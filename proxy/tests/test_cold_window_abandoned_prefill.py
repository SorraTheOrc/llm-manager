def _incident_cfg(**overrides) -> dict:
    server = {"local_admission_guard_eta_percentile_min_tokens": INCIDENT_FLOOR}
    server.update(overrides)
    return _cfg(**server)


def test_incident_row_is_priced_cold_and_admitted_at_the_shipped_deadline():
    """AC3(a): priced cold, admitted at 180 s, price inside the deadline.

    This is the correction LP-0MW0KZUUS002LICZ actually delivered: the turn
    succeeded inside its deadline. A test asserting a refusal here would need a
    hand-seeded rate the certified window does not contain.
    """
    _load_window()
    cfg = _incident_cfg()
    decision = prefill_eta.evaluate_admission(
        cfg,
        MODEL,
        INCIDENT_TOTAL,
        (INCIDENT_TOTAL - INCIDENT_NEW) / INCIDENT_TOTAL,
        "low",
        residency_measured=False,
    )
    assert decision.admit is True
    assert decision.rate_bucket == "cold"
    assert decision.capacity_basis == "cold"
    assert decision.deadline_capacity_calibrated is True
    # The cold price the row names, and the deadline it fits inside.
    assert decision.cold_ms_per_token is not None
    assert decision.eta_prefill_seconds is not None
    assert decision.eta_prefill_seconds < decision.prefill_deadline_seconds
    assert decision.eta_prefill_seconds < decision.deadline_budget_seconds
    assert decision.deadline_capacity_tokens > INCIDENT_TOTAL


def test_incident_row_is_refused_below_its_own_cold_price():
    """AC3(b): below the row's derived cold price the bound refuses it.

    The threshold is derived from the calibrated rate (no hand-picked deadline):
    ``total * cold_ms_per_token / 1000`` seconds. A deadline 10 % under it must
    refuse with the deadline-capacity reason, and the temporal bounds must still
    fit — proving the capacity is the binding constraint, not the safety budget.
    """
    _load_window()
    cfg = _incident_cfg()
    rate = _cold_capacity(INCIDENT_TOTAL, cfg).cold_ms_per_token
    assert rate is not None
    threshold_seconds = INCIDENT_TOTAL * rate / 1000.0
    deadline = threshold_seconds * 0.9

    decision = prefill_eta.evaluate_admission(
        _incident_cfg(local_prefill_deadline_seconds=deadline),
        MODEL,
        INCIDENT_TOTAL,
        (INCIDENT_TOTAL - INCIDENT_NEW) / INCIDENT_TOTAL,
        "low",
        residency_measured=False,
    )
    assert decision.admit is False
    assert decision.reason == prefill_eta.REASON_DEADLINE_CAPACITY
    assert decision.deadline_capacity_tokens < INCIDENT_TOTAL
    # The temporal bounds are satisfied: only the capacity refuses this row.
    assert decision.eta_prefill_seconds < decision.deadline_budget_seconds
    assert decision.eta_prefill_seconds < decision.prefill_deadline_seconds


